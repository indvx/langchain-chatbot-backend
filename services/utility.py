import re


# General-purpose utility helpers for data formatting and string transformations.
class UtilityService:
    def __init__(self):
        print("UtilityService initialized")

    def clean_sql_query(self, text: str) -> str:
        """
        Sanitizes raw SQL strings generated by LLMs before passing them to the DB execution tool.
        
        LLMs frequently return markdown code fences (```sql ... ```), commentary prefixes
        ('SQLQuery:'), or Markdown backticks that break SQLAlchemy execution.
        This pipeline strips all artifacts and extracts only the valid SELECT query.
        """
        # 1. Strip markdown code fences like ```sql ... ```
        block_pattern = r"```(?:sql|SQL|SQLQuery|mysql|postgresql)?\s*(.*?)\s*```"
        text = re.sub(block_pattern, r"\1", text, flags=re.DOTALL)

        # 2. Remove explanatory prefixes like "SQL Query:" or "MySQL:"
        prefix_pattern = r"^(?:SQL\s*Query|SQLQuery|MySQL|PostgreSQL|SQL)\s*:\s*"
        text = re.sub(prefix_pattern, "", text, flags=re.IGNORECASE)

        # 3. Extract pure SELECT ...; query if surrounded by conversational filler
        sql_statement_pattern = r"(SELECT.*?;)"
        sql_match = re.search(
            sql_statement_pattern, text, flags=re.IGNORECASE | re.DOTALL
        )
        if sql_match:
            text = sql_match.group(1)

        # 4. Remove backticks which some SQL dialects reject
        text = re.sub(r"`([^`]*)`", r"\1", text)

        # 5. Normalize whitespace and reformat major SQL clauses for clean logging
        text = re.sub(r"\s+", " ", text)

        keywords = ["SELECT", "FROM", "WHERE", "GROUP BY"]
        pattern = "|".join(r"\b{}\b".format(k) for k in keywords)
        text = re.sub(f"({pattern})", r"\n\1", text, flags=re.IGNORECASE)

        text = text.strip()
        text = re.sub(r"\n\s*\n", "\n", text)

        return text

